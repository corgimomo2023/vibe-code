from __future__ import annotations

import hashlib
import importlib.util
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
ARTIFACT_ROOT = Path(os.environ.get("VIBE_CODE_ROOT", ROOT))
REPORTS = ARTIFACT_ROOT / "wiki/product/reports"
EXPORTER = ROOT / "scripts/report_generation/export_vibe_reports_to_markdown.py"
STEMS = (
    "vibe-code-no-code-poc-prd-and-delivery-plan",
    "vibe-code-poc-technical-design-and-runtime-architecture",
    "vibe-code-poc-data-specification-and-schema",
)


def test_markdown_companions_are_deterministic_and_current(tmp_path: Path) -> None:
    target = tmp_path / "wiki/product/reports"
    target.mkdir(parents=True)
    for stem, suffix in zip(STEMS, (".docx", ".docx", ".xlsx"), strict=True):
        shutil.copy2(REPORTS / f"{stem}{suffix}", target / f"{stem}{suffix}")

    env = os.environ.copy()
    env["VIBE_CODE_ROOT"] = str(tmp_path)
    subprocess.run([sys.executable, str(EXPORTER)], cwd=ROOT, env=env, check=True, capture_output=True, text=True)

    for stem in STEMS:
        generated = target / f"{stem}.md"
        committed = REPORTS / f"{stem}.md"
        assert generated.read_bytes() == committed.read_bytes()
        assert "Generated by scripts/report_generation/export_vibe_reports_to_markdown.py; do not edit" in generated.read_text()


def test_markdown_mermaid_diagrams_are_canonical() -> None:
    spec = importlib.util.spec_from_file_location("markdown_exporter_under_test", EXPORTER)
    assert spec is not None and spec.loader is not None
    exporter = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(exporter)

    prd = (REPORTS / f"{STEMS[0]}.md").read_text()
    tech = (REPORTS / f"{STEMS[1]}.md").read_text()
    data = (REPORTS / f"{STEMS[2]}.md").read_text()
    state_section = "\n".join(exporter.state_mermaid_sections()).rstrip()
    use_case_section = "\n".join(exporter.use_case_mermaid_sections()).rstrip()

    assert state_section in prd and state_section in tech and state_section in data
    assert use_case_section in prd
    assert len(re.findall(r"```mermaid\nflowchart TB\n", prd)) == 9
    assert len(re.findall(r"```mermaid\nstateDiagram-v2\n", prd)) == 10
    assert len(re.findall(r"```mermaid\nstateDiagram-v2\n", tech)) == 10
    assert len(re.findall(r"```mermaid\nstateDiagram-v2\n", data)) == 10
    assert [row[0] for row in exporter.load_use_cases()] == [f"UC-{index:02d}" for index in range(1, 10)]


def test_office_artifacts_match_freeze_lock() -> None:
    freeze = json.loads((REPORTS / "vibe-code-office-freeze.json").read_text())
    assert freeze["frozen_at_commit"] == "9803da807aa04451d7311ddb257233b203cc45ac"
    for name, expected in freeze["artifacts"].items():
        assert hashlib.sha256((REPORTS / name).read_bytes()).hexdigest() == expected
