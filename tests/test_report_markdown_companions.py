from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
ARTIFACT_ROOT = Path(os.environ.get("VIBE_CODE_ROOT", ROOT))
REPORTS = ARTIFACT_ROOT / "wiki/product/reports"
EXPORTER = ROOT / "scripts/report_generation/export_vibe_reports_to_markdown.py"
STEMS = (
    "vibe-code-no-code-poc-prd-and-delivery-plan",
    "vibe-code-poc-technical-design-and-runtime-architecture",
    "vibe-code-poc-data-specification-and-schema",
)


def test_markdown_companions_are_deterministic_and_current(tmp_path: Path) -> None:
    target = tmp_path / "wiki/product/reports"
    target.mkdir(parents=True)
    for stem, suffix in zip(STEMS, (".docx", ".docx", ".xlsx"), strict=True):
        shutil.copy2(REPORTS / f"{stem}{suffix}", target / f"{stem}{suffix}")

    env = os.environ.copy()
    env["VIBE_CODE_ROOT"] = str(tmp_path)
    subprocess.run([sys.executable, str(EXPORTER)], cwd=ROOT, env=env, check=True, capture_output=True, text=True)

    for stem in STEMS:
        generated = target / f"{stem}.md"
        committed = REPORTS / f"{stem}.md"
        assert generated.read_bytes() == committed.read_bytes()
        assert "Generated by scripts/report_generation/export_vibe_reports_to_markdown.py; do not edit" in generated.read_text()
