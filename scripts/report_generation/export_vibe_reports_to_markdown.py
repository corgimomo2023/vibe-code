#!/usr/bin/env python3
"""Export deterministic, text-first Markdown companions for the three Office reports."""
from __future__ import annotations

import hashlib
import os
from pathlib import Path

from docx import Document
from docx.table import Table
from docx.text.paragraph import Paragraph
from openpyxl import load_workbook
from openpyxl.utils import get_column_letter

ROOT = Path(os.environ.get("VIBE_CODE_ROOT", Path(__file__).resolve().parents[2]))
REPORTS = ROOT / "wiki/product/reports"
PRD = "vibe-code-no-code-poc-prd-and-delivery-plan"
TECH = "vibe-code-poc-technical-design-and-runtime-architecture"
DATA = "vibe-code-poc-data-specification-and-schema"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def clean(value: object) -> str:
    text = "" if value is None else str(value)
    return " ".join(text.replace("\r", "\n").split()).replace("|", "\\|")


def front(title: str, source: Path) -> list[str]:
    return [
        "<!-- Generated by scripts/report_generation/export_vibe_reports_to_markdown.py; do not edit. -->",
        f"# {title}",
        "",
        f"- Source: `{source.name}`",
        f"- Source SHA-256: `{sha256(source)}`",
        "- Purpose: deterministic text companion for fast diff, search and AI review; Office remains the visual authority.",
        "",
    ]


def docx_blocks(document: Document):
    for child in document.element.body.iterchildren():
        if child.tag.endswith("}p"):
            yield Paragraph(child, document)
        elif child.tag.endswith("}tbl"):
            yield Table(child, document)


def export_docx(source: Path, target: Path, title: str) -> None:
    document = Document(str(source))
    lines = front(title, source)
    table_no = 0
    for block in docx_blocks(document):
        if isinstance(block, Paragraph):
            text = clean(block.text)
            if not text:
                continue
            style = block.style.name if block.style else ""
            if style.startswith("Heading"):
                try:
                    level = min(6, int(style.split()[-1]) + 1)
                except ValueError:
                    level = 2
                lines.extend([f"{'#' * level} {text}", ""])
            elif "List" in style:
                lines.append(f"- {text}")
            else:
                lines.extend([text, ""])
            continue
        table_no += 1
        rows = [[clean(cell.text) for cell in row.cells] for row in block.rows]
        width = max((len(row) for row in rows), default=0)
        if not width:
            continue
        lines.extend([f"#### Table {table_no}", ""])
        header = rows[0] + [""] * (width - len(rows[0]))
        lines.append("| " + " | ".join(header) + " |")
        lines.append("| " + " | ".join(["---"] * width) + " |")
        for row in rows[1:]:
            row += [""] * (width - len(row))
            lines.append("| " + " | ".join(row) + " |")
        lines.append("")
    target.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")


def export_xlsx(source: Path, target: Path, title: str) -> None:
    workbook = load_workbook(source, data_only=False, read_only=True)
    lines = front(title, source)
    for sheet in workbook.worksheets:
        lines.extend([f"## Sheet: {sheet.title}", "", "| Row | Non-empty cells |", "| ---: | --- |"])
        for row_no, row in enumerate(sheet.iter_rows(values_only=True), start=1):
            cells = [f"{get_column_letter(col)}{row_no}={clean(value)}" for col, value in enumerate(row, start=1) if value not in (None, "")]
            if cells:
                lines.append(f"| {row_no} | {'; '.join(cells)} |")
        lines.append("")
    workbook.close()
    target.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")


def main() -> None:
    export_docx(REPORTS / f"{PRD}.docx", REPORTS / f"{PRD}.md", "Vibe-Code No-Code POC — PRD and Delivery Plan")
    export_docx(REPORTS / f"{TECH}.docx", REPORTS / f"{TECH}.md", "Vibe-Code POC — Technical Design and Runtime Architecture")
    export_xlsx(REPORTS / f"{DATA}.xlsx", REPORTS / f"{DATA}.md", "Vibe-Code POC — Data Specification and Schema")
    print({"markdown_companions": [f"{PRD}.md", f"{TECH}.md", f"{DATA}.md"]})


if __name__ == "__main__":
    main()
